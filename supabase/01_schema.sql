--   01_schema.sql   (this file: tables, security rules, functions)
--   02_seed.sql     (associations, counties, institutions, the first churches)
--   03_admin_bootstrap.sql (after you have signed up: make yourself admin)
--
-- Security model in one paragraph:
--   Every table has row-level security (RLS) on. The browser only ever holds the
--   public "anon" key, so everything a user may do is decided here, in the
--   database. Sensitive actions (posting announcements, reviewing leaders,
--   requesting a role) go through SECURITY DEFINER functions that check the
--   caller's verified role first; the browser cannot grant itself anything.
