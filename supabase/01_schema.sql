create or replace function public.touch_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create trigger profiles_touch before update on public.profiles
  for each row execute function public.touch_updated_at();
create trigger churches_touch before update on public.churches
  for each row execute function public.touch_updated_at();

-- When a member changes institution, their open leader roles for the old
-- campus (and the old association, if it changed) are closed.
create or replace function public.profiles_close_roles_on_move()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  v_old_assoc smallint := public.institution_association_id(old.institution_id);
  v_new_assoc smallint := public.institution_association_id(new.institution_id);
begin
  if new.institution_id is distinct from old.institution_id then
    update public.leader_roles
       set status = 'revoked', reviewed_at = now(), review_note = 'Closed automatically: member changed institution.'
     where user_id = new.id and level = 'institutional' and status in ('pending', 'approved');
    if v_new_assoc is distinct from v_old_assoc then
      update public.leader_roles
         set status = 'revoked', reviewed_at = now(), review_note = 'Closed automatically: member changed association.'
       where user_id = new.id and level = 'regional' and status in ('pending', 'approved');
    end if;
  end if;
  return new;
end;
$$;
create trigger profiles_move after update of institution_id on public.profiles
  for each row execute function public.profiles_close_roles_on_move();

-- Churches: stamp who created / verified, and stop non-managers publishing.
create or replace function public.churches_stamp()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  v_manager boolean := public.can_manage_churches(new.association_id);
begin
  -- Rows written from the SQL editor / service role (no logged-in user) are trusted as-is.
  if auth.uid() is null then
    return new;
  end if;
  if tg_op = 'INSERT' then
    new.created_by := auth.uid();
    new.created_by_name := (select p.full_name from public.profiles p where p.id = auth.uid());
    if not v_manager then
      new.status := 'suggested';
      new.location_verified := false;
    end if;
  end if;
  if new.status = 'published' and (tg_op = 'INSERT' or old.status is distinct from 'published') then
    new.verified_by := auth.uid();
    new.verified_at := now();
  end if;
  return new;
end;
$$;
create trigger churches_stamp before insert or update on public.churches
  for each row execute function public.churches_stamp();

