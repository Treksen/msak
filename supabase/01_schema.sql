-- Profiles: you, leaders in scope, admins. Updates: yourself only, safe columns only.
create policy "Read own or in-scope profiles" on public.profiles for select to authenticated
  using (id = (select auth.uid()) or public.can_view_member(institution_id));
create policy "Update own profile" on public.profiles for update to authenticated
  using (id = (select auth.uid())) with check (id = (select auth.uid()));

-- Admins table: you can see whether you are one; admins see all.
create policy "See own admin row; admins see all" on public.admins for select to authenticated
  using (user_id = (select auth.uid()) or public.is_admin());

-- Leader roles: yours; admins; regional leaders see institutional roles in their association.
create policy "Read leader roles in scope" on public.leader_roles for select to authenticated
  using (
    user_id = (select auth.uid())
    or public.is_admin()
    or (level = 'institutional' and public.has_role('regional', association_id))
  );

-- Announcements: national to all members; regional to the association; institutional to the campus.
create policy "Read announcements for my audience" on public.announcements for select to authenticated
  using (
    public.is_admin()
    or (public.is_member() and (
      audience = 'national'
      or (audience = 'regional' and association_id = public.my_association_id())
      or (audience = 'institutional' and institution_id = public.my_institution_id())
      or author_id = (select auth.uid())
      or (audience <> 'national' and public.has_role('regional', association_id))
      or public.has_role('national')
    ))
  );
create policy "Authors and admins delete announcements" on public.announcements for delete to authenticated
  using (author_id = (select auth.uid()) or public.is_admin());

