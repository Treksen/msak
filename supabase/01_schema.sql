-- MSAK Portal — database schema (run 1 of 3)
-- Run in Supabase Dashboard → SQL Editor on a NEW project, in this order:
--   01_schema.sql   (this file: tables, security rules, functions)
--   02_seed.sql     (associations, counties, institutions, the first churches)
--   03_admin_bootstrap.sql (after you have signed up: make yourself admin)
--
-- Security model in one paragraph:
--   Every table has row-level security (RLS) on. The browser only ever holds the
--   public "anon" key, so everything a user may do is decided here, in the
--   database. Sensitive actions (posting announcements, reviewing leaders,
--   requesting a role) go through SECURITY DEFINER functions that check the
--   caller's verified role first; the browser cannot grant itself anything.
-- =============================================================================

create extension if not exists pgcrypto;

-- -----------------------------------------------------------------------------
-- 1. Directory: associations → counties → institutions
-- -----------------------------------------------------------------------------
create table public.associations (
  id smallint generated by default as identity primary key,
  code text not null unique check (code ~ '^[A-Z]{2,12}$'),
  name text not null check (length(btrim(name)) between 3 and 120)
);

create table public.counties (
  id bigint generated by default as identity primary key,
  association_id smallint not null references public.associations (id) on delete restrict,
  name text not null check (length(btrim(name)) between 2 and 80),
  unique (association_id, name)
);
create index counties_association_idx on public.counties (association_id);

create table public.institutions (
  id bigint generated by default as identity primary key,
  county_id bigint not null references public.counties (id) on delete restrict,
  name text not null check (length(btrim(name)) between 2 and 200),
  unique (county_id, name)
);
create index institutions_county_idx on public.institutions (county_id);

-- -----------------------------------------------------------------------------
-- 2. People: profiles, administrators, leader roles
-- -----------------------------------------------------------------------------
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text not null check (length(btrim(full_name)) between 2 and 120),
  gender text not null check (gender in ('Male', 'Female')),
  phone text not null check (phone ~ '^\+?[0-9 ()-]{7,24}$'),
  institution_id bigint not null references public.institutions (id) on delete restrict,
  course text not null check (length(btrim(course)) between 2 and 160),
  admission_year integer not null check (admission_year between 1990 and 2100),
  year_of_study integer not null check (year_of_study between 1 and 10),
  expected_completion_year integer not null,
  terms_accepted_at timestamptz not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_completion_check
    check (expected_completion_year between admission_year and admission_year + 12)
);
create index profiles_institution_idx on public.profiles (institution_id);

create table public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  granted_by uuid references auth.users (id) on delete set null,
  granted_at timestamptz not null default now()
);

create table public.leader_roles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  level text not null check (level in ('institutional', 'regional', 'national')),
  position text not null check (length(btrim(position)) between 2 and 100),
  association_id smallint references public.associations (id) on delete restrict,
  institution_id bigint references public.institutions (id) on delete restrict,
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected', 'revoked')),
  requested_at timestamptz not null default now(),
  reviewed_by uuid references auth.users (id) on delete set null,
  reviewed_at timestamptz,
  review_note text check (review_note is null or length(review_note) <= 500),
  constraint leader_roles_scope_check check (
    (level = 'institutional' and institution_id is not null and association_id is not null)
    or (level = 'regional' and association_id is not null and institution_id is null)
    or (level = 'national' and association_id is null and institution_id is null)
  )
);
-- One open (pending or approved) role per level per person.
create unique index leader_roles_one_open_uidx
  on public.leader_roles (user_id, level) where status in ('pending', 'approved');
create index leader_roles_status_idx on public.leader_roles (status, level, association_id);

-- -----------------------------------------------------------------------------
-- 3. Content: announcements, churches, documents, feedback
-- -----------------------------------------------------------------------------
create table public.announcements (
  id uuid primary key default gen_random_uuid(),
  author_id uuid references auth.users (id) on delete set null,
  author_name text not null,
  author_title text not null,
  audience text not null check (audience in ('institutional', 'regional', 'national')),
  association_id smallint references public.associations (id) on delete cascade,
  institution_id bigint references public.institutions (id) on delete cascade,
  title text not null check (length(btrim(title)) between 3 and 160),
  body text not null check (length(btrim(body)) between 1 and 5000),
  created_at timestamptz not null default now(),
  constraint announcements_scope_check check (
    (audience = 'institutional' and institution_id is not null and association_id is not null)
    or (audience = 'regional' and association_id is not null and institution_id is null)
    or (audience = 'national' and association_id is null and institution_id is null)
  )
);
create index announcements_created_idx on public.announcements (created_at desc);
create index announcements_scope_idx on public.announcements (audience, association_id, institution_id);

create table public.churches (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(btrim(name)) between 2 and 120),
  fellowship text not null check (length(btrim(fellowship)) between 2 and 160),
  association_id smallint not null references public.associations (id) on delete restrict,
  county_id bigint references public.counties (id) on delete set null,
  place text not null check (length(btrim(place)) between 2 and 200),
  lat double precision not null check (lat between -5.5 and 5.5),
  lng double precision not null check (lng between 33.5 and 42.5),
  location_verified boolean not null default false,
  phone text check (phone is null or phone ~ '^\+?[0-9 ()-]{7,24}$'),
  email text check (email is null or email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  contact_person text check (contact_person is null or length(contact_person) <= 120),
  service_times text check (service_times is null or length(service_times) <= 300),
  maps_url text check (maps_url is null or maps_url ~* '^https://'),
  photo_url text check (photo_url is null or photo_url ~* '^https://'),
  notes text check (notes is null or length(notes) <= 1000),
  status text not null default 'suggested' check (status in ('published', 'suggested', 'rejected')),
  created_by uuid references auth.users (id) on delete set null,
  created_by_name text,
  verified_by uuid references auth.users (id) on delete set null,
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index churches_status_assoc_idx on public.churches (status, association_id);

create table public.documents (
  id uuid primary key default gen_random_uuid(),
  title text not null check (length(btrim(title)) between 2 and 160),
  description text check (description is null or length(description) <= 500),
  storage_path text not null unique,
  file_name text not null,
  content_type text not null,
  size_bytes bigint not null check (size_bytes > 0),
  uploaded_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.feedback (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  message text not null check (length(btrim(message)) between 5 and 2000),
  created_at timestamptz not null default now()
);

-- -----------------------------------------------------------------------------
-- 4. Helper functions (who is the caller, what may they do)
-- -----------------------------------------------------------------------------
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.admins a where a.user_id = auth.uid());
$$;

create or replace function public.my_institution_id()
returns bigint language sql stable security definer set search_path = '' as $$
  select p.institution_id from public.profiles p where p.id = auth.uid();
$$;

create or replace function public.institution_association_id(p_institution_id bigint)
returns smallint language sql stable security definer set search_path = '' as $$
  select c.association_id
  from public.institutions i join public.counties c on c.id = i.county_id
  where i.id = p_institution_id;
$$;

create or replace function public.my_association_id()
returns smallint language sql stable security definer set search_path = '' as $$
  select public.institution_association_id(public.my_institution_id());
$$;

-- Is the caller a registered member (has a member profile)?
-- Admin/staff accounts have no profile: they are not members and are never listed anywhere.
create or replace function public.is_member()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles p where p.id = auth.uid());
$$;

-- Does the caller hold an approved role of this level (optionally in this scope)?
create or replace function public.has_role(
  p_level text, p_association_id smallint default null, p_institution_id bigint default null
)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.leader_roles r
    where r.user_id = auth.uid()
      and r.status = 'approved'
      and r.level = p_level
      and (p_association_id is null or r.association_id = p_association_id)
      and (p_institution_id is null or r.institution_id = p_institution_id)
  );
$$;

-- Admin, national leaders anywhere; regional and institutional leaders inside their association.
create or replace function public.can_manage_churches(p_association_id smallint)
returns boolean language sql stable security definer set search_path = '' as $$
  select public.is_admin()
    or public.has_role('national')
    or public.has_role('regional', p_association_id)
    or public.has_role('institutional', p_association_id);
$$;

-- Can the caller see this member's profile (leaders see members in their scope)?
create or replace function public.can_view_member(p_institution_id bigint)
returns boolean language sql stable security definer set search_path = '' as $$
  select public.is_admin()
    or public.has_role('national')
    or public.has_role('regional', public.institution_association_id(p_institution_id))
    or public.has_role('institutional', null, p_institution_id);
$$;

revoke all on function public.is_admin() from public;
revoke all on function public.is_member() from public;
revoke all on function public.my_institution_id() from public;
revoke all on function public.my_association_id() from public;
revoke all on function public.institution_association_id(bigint) from public;
revoke all on function public.has_role(text, smallint, bigint) from public;
revoke all on function public.can_manage_churches(smallint) from public;
revoke all on function public.can_view_member(bigint) from public;
grant execute on function public.is_admin() to authenticated;
grant execute on function public.is_member() to authenticated;
grant execute on function public.my_institution_id() to authenticated;
grant execute on function public.my_association_id() to authenticated;
grant execute on function public.institution_association_id(bigint) to anon, authenticated;
grant execute on function public.has_role(text, smallint, bigint) to authenticated;
grant execute on function public.can_manage_churches(smallint) to authenticated;
grant execute on function public.can_view_member(bigint) to authenticated;

